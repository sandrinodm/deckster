import type { BrandError } from '@deckster/brand';

import { loadBrand } from '@deckster/brand/node';
import * as NodeRuntime from '@effect/platform-node/NodeRuntime';
import * as NodeServices from '@effect/platform-node/NodeServices';
import { Console, Effect, FileSystem } from 'effect';
import path from 'node:path';

import { cliError, fileSystemError, type CliError, type FileSystemError } from '#cli-error.ts';
import { WORKSPACE_ROOT } from '#workspace.ts';

/**
 * The stylesheet the formatter sorts Tailwind classes against and the linter checks them against,
 * relative to the workspace root.
 */
export const TOOLING_STYLESHEET = 'tailwind.tooling.css';

/**
 * The brand whose theme the tooling stylesheet declares. Every brand has the same class names for
 * roles, type steps and spacing, so one brand is enough for sorting and linting.
 */
const TOOLING_BRAND = 'default';

/**
 * The command that writes the stylesheet, named in its header and in the error when it is stale.
 */
const REGENERATE_COMMAND = 'pnpm tooling:tailwind';

/**
 * The tooling stylesheet: Tailwind plus the default brand's theme and utilities, so `vp fmt` sorts
 * brand classes (`type-body`, `text-muted`, `p-lg`) like built-in ones and the Tailwind lint rules
 * know them. Decks never load it; they get the brand's stylesheet from `virtual:deck/brand.css`.
 *
 * @param workspaceRoot - The workspace whose `brands/default` to read.
 * @throws BrandError in the error channel when the brand does not load.
 */
export const toolingStylesheet = Effect.fn('toolingStylesheet')(function* (
  workspaceRoot: string,
): Effect.fn.Return<string, BrandError, FileSystem.FileSystem> {
  const brand = yield* loadBrand(workspaceRoot, TOOLING_BRAND);
  return [
    `/* Generated by \`${REGENERATE_COMMAND}\` from brands/${TOOLING_BRAND}; do not edit. */`,
    '@import "tailwindcss";',
    '',
    brand.compiled.tailwind,
    '',
  ].join('\n');
});

/**
 * Writes the tooling stylesheet at the workspace root, or with `check` fails when the file on disk
 * differs from what it would write.
 *
 * @param check - Whether to compare instead of writing.
 * @throws CliError in the error channel when the file is stale; FileSystemError when it cannot be
 *   read or written; BrandError when the brand does not load.
 */
export const writeToolingStylesheet = Effect.fn('writeToolingStylesheet')(function* (
  check: boolean,
): Effect.fn.Return<void, BrandError | CliError | FileSystemError, FileSystem.FileSystem> {
  const fs = yield* FileSystem.FileSystem;
  const file = path.join(WORKSPACE_ROOT, TOOLING_STYLESHEET);
  const expected = yield* toolingStylesheet(WORKSPACE_ROOT);
  if (!check) {
    yield* fs
      .writeFileString(file, expected)
      .pipe(
        Effect.mapError((error) =>
          fileSystemError('write', file, error, 'Check that the workspace root is writable.'),
        ),
      );
    return yield* Console.log(`Wrote ${TOOLING_STYLESHEET}.`);
  }

  const actual = yield* fs.readFileString(file).pipe(Effect.orElseSucceed(() => ''));
  if (actual !== expected) {
    return yield* cliError(
      `${TOOLING_STYLESHEET} does not match brands/${TOOLING_BRAND}.\n` +
        `Run \`${REGENERATE_COMMAND}\` to regenerate it.`,
    );
  }
});

/**
 * The entry point of `scripts/tailwind-tooling.ts`: writes or checks the tooling stylesheet as the
 * process's main program, printing a failure without a stack trace.
 *
 * @param check - Whether to compare instead of writing.
 */
export function runToolingStylesheet(check: boolean): void {
  NodeRuntime.runMain(
    writeToolingStylesheet(check).pipe(
      Effect.catch((error) =>
        Console.error(error.message).pipe(
          Effect.andThen(
            Effect.sync(() => {
              process.exitCode = 1;
            }),
          ),
        ),
      ),
      Effect.provide(NodeServices.layer),
    ),
  );
}
